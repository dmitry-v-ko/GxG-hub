"""Write the run part of reports/conformance/M5.json from stand/run.sh's JUnit files (conformance-matrix-v1,
«Фиксация результатов»). Keys written here are replaced; everything else in the file (acceptance, self_check,
known limits) is kept, so the hand-written evidence survives a rerun.

  uv run python stand/report.py <label>=<junit.xml> ...
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import time
import tomllib
import xml.etree.ElementTree as ET
from importlib.metadata import version
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "reports" / "conformance" / "M5.json"
MATRIX_ID = re.compile(r"test_(sc|mc)(\d\d)_")


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, check=True).stdout.strip()


def locked(package: str) -> str:
    """The version connectors/demo/uv.lock pins (the demo image installs exactly that)."""
    lock = tomllib.loads((REPO / "connectors" / "demo" / "uv.lock").read_text())
    return str(next(p["version"] for p in lock["package"] if p["name"] == package))


def run_of(path: Path) -> dict[str, Any]:
    suite = ET.parse(path).getroot()  # noqa: S314
    tests: list[dict[str, object]] = []
    by_id: dict[str, str] = {}
    for case in suite.iter("testcase"):
        failed = case.find("failure") is not None or case.find("error") is not None
        skipped = case.find("skipped") is not None
        status = "failed" if failed or skipped else "passed"  # a skip is a failure (DoD-5)
        m = MATRIX_ID.search(case.get("name", ""))
        mid = f"{m[1].upper()}-{m[2]}" if m else None
        tests.append(
            {
                "id": mid,
                "test": f"{case.get('classname')}::{case.get('name')}",
                "status": status,
                "duration_s": round(float(case.get("time", 0)), 2),
            }
        )
        if mid:
            by_id[mid] = "failed" if status == "failed" or by_id.get(mid) == "failed" else "passed"
    return {
        "matrix": dict(sorted(by_id.items())),
        "tests": tests,
        "summary": {s: sum(t["status"] == s for t in tests) for s in ("passed", "failed")},
    }


def main() -> None:
    report = json.loads(OUT.read_text()) if OUT.exists() else {}
    compose = (REPO / "compose.yaml").read_text()
    image = re.search(r"(ghcr\.io/ibm/mcp-context-forge:\S+@sha256:[0-9a-f]{64})", compose)
    runs = {}
    for arg in sys.argv[1:]:
        label, _, path = arg.partition("=")
        runs[label] = run_of(Path(path))
    report |= {
        "milestone": "M5",
        "commit": git("rev-parse", "HEAD"),
        "commit_dirty": bool(git("status", "--porcelain", "--untracked-files=no", "--", ".", ":!reports")),
        "run_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "contextforge_image": image[1] if image else None,
        "sdk_versions": {"mcp": version("mcp"), "fastmcp (demo image)": locked("fastmcp"), "PyJWT": version("PyJWT")},
        "bundle_version": json.loads((REPO / "stand" / "secrets" / "bundle" / "grants-bundle.json").read_text())[
            "bundle_version"
        ],
        "fixture_identity": "synthetic agents <name>@<tenant>.agents.gxg.example.com; keys generated by stand/init.py",
        "runs": runs,
        "all_passed": all(r["summary"]["failed"] == 0 and r["summary"]["passed"] > 0 for r in runs.values()),
    }
    OUT.write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n")
    print(json.dumps({k: v["summary"] for k, v in runs.items()}))
    sys.exit(0 if report["all_passed"] else 1)


if __name__ == "__main__":
    main()
