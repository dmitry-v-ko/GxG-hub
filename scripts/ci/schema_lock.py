#!/usr/bin/env python3
"""Lock of the normative part of every JSON Schema in ``schemas/`` (AC-M0-02).

The lock (``tests/contract/schema-lock.json``) records for each schema:

* ``required``: every ``required`` array, keyed by JSON pointer — readable in
  review, so dropping a mandatory field is visible in the diff;
* ``normative_sha256``: SHA-256 of the schema with annotations (``title``,
  ``description``, ``$comment``, ``examples``) removed.

The OpenAPI document (``schemas/*.openapi.yaml``, whose components embed JSON
Schemas) is locked by the SHA-256 of its parsed content.

``tests/contract/test_schema_lock.py`` fails when a schema no longer matches
the lock, so any normative schema change (and any deleted or added schema)
turns CI red until the lock is regenerated in the same PR, deliberately and
only after the spec in ``docs/specs/`` that calls for the change is updated
(weakening needs a CODEOWNERS security review):

    uv run python scripts/ci/schema_lock.py --write

Regenerating the lock does not silence
``tests/contract/test_security_required_fields.py``: security-critical fields
are pinned there independently of the lock.

Wording-only changes to titles and descriptions do not touch the lock.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS = ROOT / "schemas"
LOCK = ROOT / "tests" / "contract" / "schema-lock.json"

ANNOTATIONS = frozenset({"title", "description", "$comment", "examples"})
# Keywords whose value maps arbitrary names (property names!) to subschemas.
NAMED_SUBSCHEMAS = frozenset({"properties", "patternProperties", "$defs", "definitions", "dependentSchemas"})
SUBSCHEMA = frozenset(
    {
        "items",
        "not",
        "if",
        "then",
        "else",
        "additionalProperties",
        "contains",
        "propertyNames",
        "unevaluatedProperties",
        "unevaluatedItems",
        "additionalItems",
    }
)
SUBSCHEMA_LIST = frozenset({"allOf", "anyOf", "oneOf", "prefixItems"})


def _escape(token: str) -> str:
    return token.replace("~", "~0").replace("/", "~1")


def normative(node: Any) -> Any:
    """Schema without annotation keywords; property names are never touched."""
    if not isinstance(node, dict):
        return node
    out: dict[str, Any] = {}
    for key, value in node.items():
        if key in ANNOTATIONS:
            continue
        if key in NAMED_SUBSCHEMAS and isinstance(value, dict):
            out[key] = {name: normative(sub) for name, sub in value.items()}
        elif key in SUBSCHEMA:
            out[key] = normative(value)
        elif key in SUBSCHEMA_LIST and isinstance(value, list):
            out[key] = [normative(sub) for sub in value]
        else:
            out[key] = value
    return out


def required_map(node: Any, pointer: str = "") -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    if not isinstance(node, dict):
        return found
    req = node.get("required")
    if isinstance(req, list):
        found[pointer or "/"] = sorted(str(r) for r in req)
    for key, value in node.items():
        here = f"{pointer}/{_escape(key)}"
        if key in NAMED_SUBSCHEMAS and isinstance(value, dict):
            for name, sub in value.items():
                found.update(required_map(sub, f"{here}/{_escape(name)}"))
        elif key in SUBSCHEMA:
            found.update(required_map(value, here))
        elif key in SUBSCHEMA_LIST and isinstance(value, list):
            for i, sub in enumerate(value):
                found.update(required_map(sub, f"{here}/{i}"))
    return found


def schema_entry(schema: Any) -> dict[str, Any]:
    canon = json.dumps(normative(schema), sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return {
        "required": required_map(schema),
        "normative_sha256": hashlib.sha256(canon.encode("utf-8")).hexdigest(),
    }


def document_sha256(path: Path) -> str:
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    canon = json.dumps(doc, sort_keys=True, ensure_ascii=False, separators=(",", ":"), default=str)
    return hashlib.sha256(canon.encode("utf-8")).hexdigest()


def build_lock(schemas_dir: Path = SCHEMAS) -> dict[str, Any]:
    return {
        "comment": "Generated by scripts/ci/schema_lock.py --write. Do not edit by hand.",
        "schemas": {
            p.name: schema_entry(json.loads(p.read_text(encoding="utf-8")))
            for p in sorted(schemas_dir.glob("*.schema.json"))
        },
        "documents": {p.name: document_sha256(p) for p in sorted(schemas_dir.glob("*.openapi.yaml"))},
    }


def render(lock: dict[str, Any]) -> str:
    return json.dumps(lock, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="regenerate the lock file")
    args = parser.parse_args(argv)
    text = render(build_lock())
    if args.write:
        LOCK.write_text(text, encoding="utf-8")
        print(f"wrote {LOCK.relative_to(ROOT)}")
        return 0
    if not LOCK.exists() or LOCK.read_text(encoding="utf-8") != text:
        print(
            "schema lock is out of date. First make sure docs/specs/ calls for this schema change "
            "(change the spec first, CODEOWNERS review for any weakening); only then run "
            "`uv run python scripts/ci/schema_lock.py --write`.",
            file=sys.stderr,
        )
        return 1
    print("schema lock is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
